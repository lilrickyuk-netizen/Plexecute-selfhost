/**
 * Step 92 credential readiness. Every env var the server reads is listed here with the file
 * that consumes it, so a test proves no integration is a shell: the code path exists and only
 * the value is missing. kind: owner = real provider credential/approval from the owner;
 * generated = random internal secret (already created); platform = managed by the hosting platform;
 * setting = optional non-secret configuration.
 */
export type CredKind = "owner" | "generated" | "platform" | "setting";
export type Cred = {
  name: string;
  integration: string;
  kind: CredKind;
  required: boolean;
  consumer: string;
  obtain: string;
};

const o = (
  name: string,
  integration: string,
  consumer: string,
  obtain: string,
  required = true,
): Cred => ({ name, integration, kind: "owner", required, consumer, obtain });
const s = (name: string, integration: string, consumer: string, obtain: string): Cred => ({
  name,
  integration,
  kind: "setting",
  required: false,
  consumer,
  obtain,
});
const g = (name: string, integration: string, consumer: string): Cred => ({
  name,
  integration,
  kind: "generated",
  required: true,
  consumer,
  obtain: "Created automatically",
});
const p = (name: string, integration: string, consumer: string): Cred => ({
  name,
  integration,
  kind: "platform",
  required: true,
  consumer,
  obtain: "From your Supabase project → Settings → API",
});

